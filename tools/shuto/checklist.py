"""Generate the Shuto route checklist (docs/shuto/route_checklist.md) from the data, never by hand.

Per manifest route: era status, network km per direction (data/shuto/network.json), graph
connectivity, and per-category coverage tracked separately: geometry, scenery, signs, collision,
routing, traffic, activities. Coverage is measured from the generated sections: a carriageway
counts for a category when the corresponding generated output exists for its section bbox and
(for driving) when traversal events passed over it.
Usage: python -I tools/shuto/checklist.py
"""
import glob
import json
import math
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
sys.path.insert(0, os.path.dirname(__file__))
from make_activities import SECTIONS  # noqa: E402


def plan_len(P):
    return sum(math.hypot(b[0] - a[0], b[2] - a[2]) for a, b in zip(P, P[1:]))


def main():
    sys.stdout.reconfigure(encoding='utf-8')
    man = json.load(open(os.path.join(ROOT, 'docs', 'shuto', 'route_manifest.json'), encoding='utf-8'))
    net = json.load(open(os.path.join(ROOT, 'data', 'shuto', 'network.json'), encoding='utf-8'))
    # Connectivity: weakly connected components over nodes.
    parent = {}

    def find(a):
        while parent.setdefault(a, a) != a:
            parent[a] = parent[parent[a]]
            a = parent[a]
        return a
    for c in net['carriageways']:
        parent[find(c['from'])] = find(c['to'])
    comp_size = {}
    for c in net['carriageways']:
        r = find(c['from'])
        comp_size[r] = comp_size.get(r, 0) + 1
    main_comp = max(comp_size, key=comp_size.get)

    # Section coverage.
    built, driven = {}, {}
    for name, cfg in SECTIONS.items():
        sec = os.path.join(ROOT, 'models', 'shuto', name)
        x0, z0, x1, z1 = cfg['bbox']
        has = {
            'geometry': bool(glob.glob(os.path.join(sec, 'render', '*.glb'))),
            'collision': bool(glob.glob(os.path.join(sec, 'collision', '*_col.glb'))),
            'scenery': bool(glob.glob(os.path.join(sec, 'scenery', '*.glb')) or glob.glob(os.path.join(sec, 'scenery', '*.gltf'))),
            'signs': os.path.exists(os.path.join(sec, 'signs.glb')),
        }
        for c in net['carriageways']:
            n_in = sum(1 for p in c['points'] if x0 <= p[0] <= x1 and z0 <= p[2] <= z1)
            if n_in >= 2:
                frac = n_in / len(c['points'])
                for k, v in has.items():
                    if v:
                        built.setdefault(c['id'], {})[k] = max(built.get(c['id'], {}).get(k, 0.0), frac)
        res = os.path.join(ROOT, 'data', 'shuto', f'traversal_{name}_results.json')
        if os.path.exists(res):
            for r in json.load(open(res, encoding='utf-8'))['results']:
                ok = r['finished'] and not r['stuck'] and not r['fell'] and not r['no_ground_recoveries']
                for cid in r['carriageways']:
                    driven[cid] = driven.get(cid, False) or ok
        acts = os.path.join(ROOT, 'data', 'shuto', f'activities_{name}.json')
        if os.path.exists(acts):
            for e in json.load(open(acts, encoding='utf-8'))['events']:
                for cid in e.get('route_carriageways', []):
                    built.setdefault(cid, {})['activities'] = 1.0

    lines = ['# Shuto Expressway route checklist (generated)', '',
             f"Reference date {man['reference_date']}. Generated by `tools/shuto/checklist.py` from "
             '`docs/shuto/route_manifest.json`, `data/shuto/network.json`, the generated sections and the '
             'traversal results. Percentages are shares of route length (both directions).', '',
             'Columns: **net km** = carriageway km in the dataset (IN/CW + OUT/CCW incl. ramps); **graph** = '
             'all carriageways in the main connected component; then the share of route length that has '
             'generated geometry, collision, scenery, signs, passed scripted traversal (driven), and an '
             'activity. Traffic is not implemented anywhere (0 %).', '',
             '| Route | Name | Era status | net km | graph | geometry | collision | scenery | signs | driven | activities | traffic |',
             '|---|---|---|---|---|---|---|---|---|---|---|---|']
    totals = {k: [0.0, 0.0] for k in ('geometry', 'collision', 'scenery', 'signs', 'driven', 'activities')}
    for r in man['routes']:
        segs = r.get('segments', [])
        st = sorted({s.get('status_at_reference', '?') for s in segs}) or ['no data']
        cws = [c for c in net['carriageways'] if c['route'] == r['id']]
        km = sum(plan_len(c['points']) for c in cws) / 1000.0
        conn = all(find(c['from']) == main_comp for c in cws) if cws else False
        cells = []
        for k in ('geometry', 'collision', 'scenery', 'signs', 'driven', 'activities'):
            L = covered = 0.0
            for c in cws:
                l = plan_len(c['points'])
                L += l
                if k == 'driven':
                    covered += l * built.get(c['id'], {}).get('geometry', 0.0) if driven.get(c['id']) else 0.0
                else:
                    covered += l * built.get(c['id'], {}).get(k, 0.0)
            totals[k][0] += covered
            totals[k][1] += L
            cells.append(f'{100.0 * covered / L:.0f} %' if L > 0 else '-')
        lines.append(f"| {r['id']} | {r.get('name_en', '')} | {', '.join(st)} | {km:.1f} | "
                     f"{'yes' if conn else ('no' if cws else '-')} | " + ' | '.join(cells) + ' | 0 % |')
    lines += ['', '**Whole network:** ' + ', '.join(f'{k} {100.0 * c / max(L, 1):.1f} %' for k, (c, L) in totals.items()) +
              ', traffic 0 %.', '',
              f"Carriageways: {len(net['carriageways'])}; main connected component: {comp_size[main_comp]}; "
              f"other components: {len(comp_size) - 1} (PA lot roads and unassigned ramps, see build_report.json).", '',
              '## Not in era / closed / historical', '']
    for r in man['routes']:
        for s in r.get('segments', []):
            if s.get('status_at_reference') in ('not_yet_open', 'closed_later'):
                lines.append(f"- {r['id']} {s.get('from', '')} - {s.get('to', '')}: {s.get('status_at_reference')} "
                             f"(opened {s.get('opened')}) {s.get('notes') or ''}".rstrip())
    for h in man.get('closed_or_historical', []):
        lines.append(f"- historical: {json.dumps(h, ensure_ascii=False)}")
    out = os.path.join(ROOT, 'docs', 'shuto', 'route_checklist.md')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print('wrote', out)
    print('\n'.join(lines[8:8 + len(man['routes']) + 3]))


if __name__ == '__main__':
    main()
